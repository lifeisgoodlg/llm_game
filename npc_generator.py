# NPC 대사 생성
def generate_npc_dialogue(llm: ChatOpenAI, npc_name: str, npc_info: dict, relationship_score: int, context: str, history: list = None) -> dict:
    NL = chr(10)
    recent = (history or [])[-6:]
    if recent:
        speaker_name = npc_info.get("이름", npc_name)
        lines = [
            f"{'주인공' if msg['role'] == 'player' else speaker_name}: {msg['text']}"
            for msg in recent
        ]
        history_block = "지금까지 나눈 대화:" + NL + NL.join(lines)
    else:
        history_block = "아직 나눈 대화가 없습니다. 이번이 첫 대면입니다."

    prompt = f"""
조선 궁중의 NPC 대사를 생성하세요. 반드시 JSON 형태로만 출력합니다.

NPC 정보:
- 배역: {npc_name}
- 이름: {npc_info.get('이름', npc_name)}
- 성격: {npc_info.get('성격', '')}
- 말투: {npc_info.get('말투', '')}
- 주요욕망: {npc_info.get('주요욕망', '')}
- 현재 관계 점수: {relationship_score}/100

{history_block}

주인공이 방금 건넨 말: {context}

규칙:
- 관계 점수가 높으면 호의적이거나 협조적인 느낌
- 관계 점수가 낮으면 경계하거나 떠보는 느낌
- 우호후궁이라도 관계가 낮으면 무조건 돕지 않음
- 대비는 주인공의 야심을 이미 눈치채고 있다는 서늘함이 배어야 함
- 영의정은 사사로운 정이 아니라 이해득실로 움직임
- 앞서 나눈 대화를 기억하고 이어서 말하세요. 같은 인사나 첫 대면 인사를 반복하지 마세요.
- 조선 궁중의 호칭과 말투를 쓰세요 (전하, 마마, 소인, 아뢰옵니다 등)

{{
  "대사": "1~2문장 대사",
  "속내": "겉으로 말하지 않은 진짜 의도 1문장",
  "관계변화제안": -10~10 사이 정수
}}"""

    return invoke_json(
        llm,
        WRITER_SYSTEM,
        prompt,
        validate=lambda d: "대사" in d,
    )
